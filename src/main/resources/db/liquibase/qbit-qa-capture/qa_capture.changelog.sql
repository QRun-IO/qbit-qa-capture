-- changeset qbit-qa-capture:1
-- comment: QA Capture Settings. One row per environment (matching the QBit config's environment name, for example prod): the provider, its team id and reusable recording link, the capture mode and extra blur selectors. Not seeded: the host adds its own row.
CREATE TABLE IF NOT EXISTS qa_capture_settings (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   environment VARCHAR(50) NOT NULL,
   provider VARCHAR(50) DEFAULT 'jam' NOT NULL,
   team_id VARCHAR(100),
   recording_link_id VARCHAR(100),
   mode VARCHAR(30) DEFAULT 'OFF' NOT NULL,
   extra_blur_selectors TEXT,
   notes TEXT,
   create_date TIMESTAMP WITHOUT TIME ZONE,
   modify_date TIMESTAMP WITHOUT TIME ZONE,
   CONSTRAINT pk_qa_capture_settings PRIMARY KEY (id),
   CONSTRAINT uq_qa_capture_settings_environment UNIQUE (environment)
);

-- changeset qbit-qa-capture:2
-- comment: QA Capture Audience. Users (USER: user id or email) and roles (ROLE: a name the host's role resolver returns, by default the session's permission names) for whom capture is on in the AUDIENCE modes. Rows with source QA_MODE hold a user's self-serve QA mode switch when the host has no core key-value preference store.
CREATE TABLE IF NOT EXISTS qa_capture_audience (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   settings_id BIGINT NOT NULL,
   audience_type VARCHAR(10) NOT NULL,
   value VARCHAR(250) NOT NULL,
   source VARCHAR(20) DEFAULT 'ADMIN' NOT NULL,
   active BOOLEAN DEFAULT TRUE NOT NULL,
   notes TEXT,
   create_date TIMESTAMP WITHOUT TIME ZONE,
   modify_date TIMESTAMP WITHOUT TIME ZONE,
   CONSTRAINT pk_qa_capture_audience PRIMARY KEY (id),
   CONSTRAINT uq_qa_capture_audience_member UNIQUE (settings_id, audience_type, value, source)
);
CREATE INDEX IF NOT EXISTS idx_qa_capture_audience_settings ON qa_capture_audience (settings_id, active);

-- changeset qbit-qa-capture:3
-- comment: QA Capture Sanitizer Rules. What captures redact: header names, JSON/form body fields, URL query parameters, value patterns (valid in Java and JavaScript), dropped same-origin path prefixes and blur selectors. BUILT_IN rows are seeded by changeset 5, SECURED_DATA rows are added at startup for fields the instance marks secure, ADMIN rows by administrators. Active rows are the rule set served to clients.
CREATE TABLE IF NOT EXISTS qa_capture_sanitizer_rule (
   id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   rule_type VARCHAR(20) NOT NULL,
   value VARCHAR(500) NOT NULL,
   source VARCHAR(20) DEFAULT 'ADMIN' NOT NULL,
   source_ref VARCHAR(250),
   active BOOLEAN DEFAULT TRUE NOT NULL,
   description VARCHAR(500),
   create_date TIMESTAMP WITHOUT TIME ZONE,
   modify_date TIMESTAMP WITHOUT TIME ZONE,
   CONSTRAINT pk_qa_capture_sanitizer_rule PRIMARY KEY (id),
   CONSTRAINT uq_qa_capture_sanitizer_rule UNIQUE (rule_type, value)
);

-- changeset qbit-qa-capture:4
